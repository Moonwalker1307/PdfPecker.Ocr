using System.Globalization;
using System.Text;

namespace TesseractComparison;

/// <summary>One CSV row of a measuring child.</summary>
sealed class ResultRow
{
    public required Dictionary<string, string> Fields { get; init; }

    public string this[string key] => Fields.GetValueOrDefault(key, "");
    public double Num(string key) => double.TryParse(this[key], NumberStyles.Float, CultureInfo.InvariantCulture, out var v) ? v : double.NaN;
    public bool Failed => this["error"].Length > 0 || double.IsNaN(Num("cer"));
    public string Config => $"{this["engine"]}/{this["threads"]}";
}

/// <summary>Turns the per-page CSV rows of all configurations into the Markdown report.</summary>
static class Report
{
    public static List<ResultRow> ReadRows(string csvPath)
    {
        var rows = new List<ResultRow>();
        string[]? header = null;
        foreach (var line in File.ReadLines(csvPath, Encoding.UTF8))
        {
            if (line.Length == 0) continue;
            var cells = SplitCsv(line);
            if (header is null) { header = cells; continue; }
            var d = new Dictionary<string, string>();
            for (int i = 0; i < header.Length && i < cells.Length; i++) d[header[i]] = cells[i];
            rows.Add(new ResultRow { Fields = d });
        }
        return rows;
    }

    static string[] SplitCsv(string line)
    {
        var cells = new List<string>();
        var sb = new StringBuilder();
        bool quoted = false;
        for (int i = 0; i < line.Length; i++)
        {
            char c = line[i];
            if (quoted)
            {
                if (c == '"' && i + 1 < line.Length && line[i + 1] == '"') { sb.Append('"'); i++; }
                else if (c == '"') quoted = false;
                else sb.Append(c);
            }
            else if (c == '"') quoted = true;
            else if (c == ',') { cells.Add(sb.ToString()); sb.Clear(); }
            else sb.Append(c);
        }
        cells.Add(sb.ToString());
        return cells.ToArray();
    }

    static string Pct(double v) => double.IsNaN(v) ? "n/a" : (v * 100).ToString("0.00", CultureInfo.InvariantCulture) + "%";
    static string Ms(double v) => double.IsNaN(v) ? "n/a" : v >= 100 ? v.ToString("0", CultureInfo.InvariantCulture) : v.ToString("0.0", CultureInfo.InvariantCulture);
    static double Median(IEnumerable<double> values)
    {
        var l = values.Where(v => !double.IsNaN(v)).OrderBy(v => v).ToList();
        if (l.Count == 0) return double.NaN;
        return l.Count % 2 == 1 ? l[l.Count / 2] : (l[l.Count / 2 - 1] + l[l.Count / 2]) / 2;
    }
    static double Mean(IEnumerable<double> values)
    {
        var l = values.Where(v => !double.IsNaN(v)).ToList();
        return l.Count == 0 ? double.NaN : l.Average();
    }

    // Micro averages weight every character (or word) alike, so long pages count more; macro averages weight every page alike.
    static double MicroCer(IReadOnlyCollection<ResultRow> rows) => rows.Count == 0 ? double.NaN : rows.Sum(r => r.Num("char_edits")) / Math.Max(1, rows.Sum(r => r.Num("ref_chars")));
    static double MicroWer(IReadOnlyCollection<ResultRow> rows) => rows.Count == 0 ? double.NaN : rows.Sum(r => r.Num("word_edits")) / Math.Max(1, rows.Sum(r => r.Num("ref_words")));

    public static string Build(string dir, List<ResultRow> all, Dictionary<string, Dictionary<string, string>> meta, string title)
    {
        var configs = all.Select(r => r.Config).Distinct().OrderBy(c => c, StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.AppendLine($"# {title}").AppendLine();
        sb.AppendLine("Generated by `bench/TesseractComparison`. All engines read the same synthetic corpus (`tools/Corpus`), one engine and thread count per fresh process.").AppendLine();
        sb.AppendLine("## Engines").AppendLine();
        foreach (var (cfg, m) in meta.OrderBy(k => k.Key, StringComparer.Ordinal))
            sb.AppendLine($"- `{cfg}`: {m.GetValueOrDefault("description")}. Start-up {m.GetValueOrDefault("init_ms")} ms plus first model load {m.GetValueOrDefault("first_prepare_ms")} ms, {m.GetValueOrDefault("rss_after_load_mb")} MB resident after loading, {m.GetValueOrDefault("runs")} timed runs after {m.GetValueOrDefault("warmup")} warm-up per page.");
        sb.AppendLine();
        sb.AppendLine("## Summary").AppendLine();
        sb.AppendLine("| Config | Pages | CER (all text) | CER (mean of pages) | WER (all text) | Word bag F1 | Box recall @IoU 0.5 | Time per page, median (ms) | Time per page, mean (ms) | CPU per page, mean (ms) | Peak RSS per page, median / max (MB) | Failed |");
        sb.AppendLine("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
        foreach (var cfg in configs)
        {
            var rows = all.Where(r => r.Config == cfg).ToList();
            var ok = rows.Where(r => !r.Failed).ToList();
            sb.AppendLine($"| {cfg} | {ok.Count} | {Pct(MicroCer(ok))} | {Pct(Mean(ok.Select(r => r.Num("cer"))))} | {Pct(MicroWer(ok))} | {Mean(ok.Select(r => r.Num("bag_f1"))).ToString("0.000", CultureInfo.InvariantCulture)} | {Pct(Mean(ok.Select(r => r.Num("box_recall_iou50"))))} | {Ms(Median(ok.Select(r => r.Num("wall_ms_median"))))} | {Ms(Mean(ok.Select(r => r.Num("wall_ms_median"))))} | {Ms(Mean(ok.Select(r => r.Num("cpu_ms_median"))))} | {Median(ok.Select(r => r.Num("peak_rss_mb"))).ToString("0", CultureInfo.InvariantCulture)} / {(ok.Count == 0 ? 0 : ok.Max(r => r.Num("peak_rss_mb"))).ToString("0", CultureInfo.InvariantCulture)} | {rows.Count - ok.Count} |");
        }
        sb.AppendLine();
        var managed = all.Where(r => !r.Failed && r.Num("alloc_mb") > 0).GroupBy(r => r.Config).ToList();
        if (managed.Count > 0)
        {
            sb.AppendLine("Managed allocation per page (mean): " + string.Join(", ", managed.Select(g => $"{g.Key} {Mean(g.Select(r => r.Num("alloc_mb"))).ToString("0.0", CultureInfo.InvariantCulture)} MB")) + ".").AppendLine();
        }

        // Condition groups. Degraded pages are all 300 dpi; "clean 300" and "clean 150" are the undegraded renderings.
        var groups = new List<(string Name, Func<ResultRow, bool> Match)>
        {
            ("clean, 300 dpi", r => r["degradation"] == "none" && r["dpi"] == "300"),
            ("clean, 150 dpi", r => r["degradation"] == "none" && r["dpi"] == "150"),
        };
        if (all.Any(r => r["category"] == "tesseract-sample")) groups.Add(("Tesseract's sample images", r => r["category"] == "tesseract-sample"));
        foreach (var d in all.Select(r => r["degradation"]).Where(d => d != "none").Distinct().OrderBy(d => d, StringComparer.Ordinal))
        {
            string name = d;
            groups.Add(($"degraded: {name}", r => r["degradation"] == name));
        }
        foreach (var c in all.Select(r => r["category"]).Distinct().OrderBy(c => c, StringComparer.Ordinal))
        {
            string name = c;
            groups.Add(($"clean 300 dpi, {name}", r => r["degradation"] == "none" && r["dpi"] == "300" && r["category"] == name));
        }
        foreach (var l in all.Select(r => r["lang"]).Distinct().OrderBy(l => l, StringComparer.Ordinal))
        {
            string name = l;
            groups.Add(($"clean 300 dpi, language {name}", r => r["degradation"] == "none" && r["dpi"] == "300" && r["lang"] == name));
        }

        Table(sb, "Character error rate by condition", configs, groups, all, rows => Pct(MicroCer(rows)));
        Table(sb, "Word error rate by condition", configs, groups, all, rows => Pct(MicroWer(rows)));
        Table(sb, "Word bag F1 by condition (ignores reading order)", configs, groups, all, rows => Mean(rows.Select(r => r.Num("bag_f1"))).ToString("0.000", CultureInfo.InvariantCulture));
        Table(sb, "Median time per page by condition (ms)", configs, groups, all, rows => Ms(Median(rows.Select(r => r.Num("wall_ms_median")))));
        Table(sb, "Peak resident memory by condition, median (MB)", configs, groups, all, rows => Median(rows.Select(r => r.Num("peak_rss_mb"))).ToString("0", CultureInfo.InvariantCulture));

        sb.AppendLine("## Per page").AppendLine();
        sb.AppendLine("Character error rate and median time per page, one column pair per configuration. `-` is a failed page.").AppendLine();
        sb.Append("| Page |");
        foreach (var c in configs) sb.Append($" {c} CER | {c} ms |");
        sb.AppendLine();
        sb.Append("| --- |");
        foreach (var _ in configs) sb.Append(" ---: | ---: |");
        sb.AppendLine();
        foreach (var page in all.Select(r => r["page"]).Distinct().OrderBy(p => p, StringComparer.Ordinal))
        {
            sb.Append($"| {page} |");
            foreach (var c in configs)
            {
                var r = all.FirstOrDefault(x => x.Config == c && x["page"] == page);
                sb.Append(r is null || r.Failed ? " - | - |" : $" {Pct(r.Num("cer"))} | {Ms(r.Num("wall_ms_median"))} |");
            }
            sb.AppendLine();
        }
        var failures = all.Where(r => r.Failed).ToList();
        if (failures.Count > 0)
        {
            sb.AppendLine().AppendLine("## Failures").AppendLine();
            foreach (var r in failures) sb.AppendLine($"- {r.Config} {r["page"]}: {r["error"]}");
        }
        return sb.ToString();
    }

    static void Table(StringBuilder sb, string title, List<string> configs, List<(string Name, Func<ResultRow, bool> Match)> groups, List<ResultRow> all,
        Func<IReadOnlyCollection<ResultRow>, string> cell)
    {
        sb.AppendLine($"## {title}").AppendLine();
        sb.AppendLine("| Condition | Pages | " + string.Join(" | ", configs) + " |");
        sb.AppendLine("| --- | ---: |" + string.Concat(configs.Select(_ => " ---: |")));
        foreach (var (name, match) in groups)
        {
            int pages = all.Where(match).Select(r => r["page"]).Distinct().Count();
            if (pages == 0) continue;
            sb.Append($"| {name} | {pages} |");
            foreach (var c in configs)
            {
                var rows = all.Where(r => r.Config == c && match(r) && !r.Failed).ToList();
                sb.Append($" {(rows.Count == 0 ? "n/a" : cell(rows))} |");
            }
            sb.AppendLine();
        }
        sb.AppendLine();
    }
}
